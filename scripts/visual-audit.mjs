import { chromium } from 'playwright'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import assert from 'node:assert/strict'

const output = new URL('../docs/screenshots/one-click/layout/', import.meta.url)
await mkdir(output, { recursive: true })
console.log('Launching Chromium')
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, timeout: 20000 })
console.log('Browser ready')
const results = []
const base = process.env.QA_BASE_URL || 'http://127.0.0.1:5173/'
const youtubeIds = ['oF7MRtebWHs', '9FwdP60SSpc', 'QstQJOrkq2k', 'rwz_finz-Y0', 'fCXZFommLOA', 'bnOoqp2OafA']
try {
  for (const width of [390, 768, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: 'reduce' })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    console.log(`Auditing ${width}px`)
    await page.route('https://**/*', route => route.abort())
    await page.goto(base, { waitUntil: 'networkidle', timeout: 20000 })
    await page.waitForFunction(() => document.documentElement.dataset.fontSource)
    await page.evaluate(() => document.fonts.ready)
    const dimensions = await page.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth, headings: [...document.querySelectorAll('h2')].map(heading => heading.textContent), skills: document.querySelectorAll('.skill-card').length, fontSource: document.documentElement.dataset.fontSource, loadedFontFaces: [...document.fonts].filter(face => face.status === 'loaded').map(face => face.family), heroVideo: document.querySelector('.hero-video').getBoundingClientRect().top, heroText: document.querySelector('.hero-copy').getBoundingClientRect().top }))
    assert.ok(dimensions.content <= width, `Overflow at ${width}px`)
    assert.equal(dimensions.skills, 7)
    assert.deepEqual(dimensions.headings, ['De onde vim e onde cheguei: A Jornada', 'Acervo de contos Portfólio', 'O meu arsenal O Grimório', 'Feedbacks Dos Clientes', 'Vamos contar A Sua História?'])
    if (width < 1050) {
      assert.ok(dimensions.heroVideo < dimensions.heroText)
      const journeyImage = await page.locator('.journey-art img').boundingBox()
      const epilogueImage = await page.locator('.epilogue-art img').boundingBox()
      assert.ok(Math.abs(journeyImage.width / journeyImage.height - 5 / 3) < .01, 'Journey illustration keeps its landscape ratio on mobile')
      assert.ok(Math.abs(epilogueImage.width / epilogueImage.height - 2) < .01, 'Epilogue illustration keeps its landscape ratio on mobile')
      const menu = page.locator('.menu-toggle')
      await menu.click()
      await page.getByRole('button', { name: 'Fechar menu' }).waitFor()
      assert.equal(await menu.getAttribute('aria-expanded'), 'true')
      await page.locator('#main-navigation a').first().focus()
      await page.keyboard.press('Escape')
      await page.getByRole('button', { name: 'Abrir menu' }).waitFor()
      assert.equal(await menu.getAttribute('aria-expanded'), 'false')
      assert.ok(await menu.evaluate(element => element === document.activeElement))
    }
    assert.equal(await page.locator('iframe').count(), 2, 'The two visible cards prepare their players without starting playback')
    assert.equal(await page.locator('.youtube-card.is-playing').count(), 0)
    assert.equal(await page.locator('.hero-video .youtube-host').getAttribute('aria-hidden'), 'true')
    await page.getByRole('link', { name: 'Assista ao demoreel' }).click()
    const heroFrame = page.locator('.hero-video iframe')
    await heroFrame.waitFor({ state: 'attached' })
    assert.match(await heroFrame.getAttribute('src'), /\/embed\/9FwdP60SSpc\?/)
    assert.equal(await heroFrame.getAttribute('referrerpolicy'), 'strict-origin-when-cross-origin')
    const embed = new URL(await heroFrame.getAttribute('src'))
    assert.equal(embed.searchParams.get('autoplay'), '0', 'No playback on page load')
    assert.equal(embed.searchParams.get('enablejsapi'), '1')
    await page.waitForFunction(() => document.activeElement === document.querySelector('.hero-video iframe') || document.activeElement === document.querySelector('.hero-video .video-frame'))
    const heroPlayerDimensions = await page.locator('.hero-video .youtube-player').boundingBox()
    assert.ok(Math.abs(heroPlayerDimensions.width / heroPlayerDimensions.height - 9 / 16) < .01, 'Presentation keeps the vertical video ratio')
    await page.locator('.hero-video').getByRole('button', { name: 'Voltar à capa' }).click()
    assert.equal(await page.locator('.hero-video .youtube-host').getAttribute('aria-hidden'), 'true')
    await page.waitForFunction(() => document.activeElement?.matches('.hero-video .youtube-launch'))
    await page.locator('.hero-video .youtube-launch').press('Enter')
    await heroFrame.waitFor({ state: 'attached' })
    assert.equal(await page.locator('.gallery-dots button').count(), 6)
    const gallery = page.locator('.portfolio-stage')
    for (const id of youtubeIds) {
      const thumbnail = gallery.locator('.youtube-launch img')
      await thumbnail.scrollIntoViewIfNeeded()
      await thumbnail.evaluate(element => element.decode())
      assert.match(await thumbnail.getAttribute('src'), new RegExp(`${id}-hd\\.jpg$`))
      assert.equal(await gallery.getByRole('link', { name: 'Abrir no YouTube' }).getAttribute('href'), `https://www.youtube.com/shorts/${id}`)
      const playerDimensions = await gallery.locator('.youtube-player').boundingBox()
      assert.ok(Math.abs(playerDimensions.width / playerDimensions.height - 9 / 16) < .01, 'Portrait player keeps the 9:16 ratio')
      assert.ok(playerDimensions.width >= 200 && playerDimensions.height >= 200)
      await gallery.getByRole('button', { name: /^Reproduzir / }).click()
      const frame = gallery.locator('iframe')
      await frame.waitFor({ state: 'attached' })
      assert.match(await frame.getAttribute('src'), new RegExp(`^https://www\\.youtube-nocookie\\.com/embed/${id}\\?`))
      assert.equal(await page.locator('.hero-video.is-playing').count(), 0, 'Starting a gallery video stops the presentation')
      assert.equal(await page.locator('.hero-video .youtube-host').getAttribute('aria-hidden'), 'true')
      await page.getByRole('button', { name: 'Próximo projeto', exact: true }).click()
      assert.equal(await gallery.locator('.youtube-card.is-playing').count(), 0, 'Changing projects stops playback and restores the cover')
    }
    await page.getByRole('button', { name: 'Projeto anterior', exact: true }).click()
    assert.match(await gallery.locator('img').getAttribute('src'), /bnOoqp2OafA/)
    await page.getByRole('button', { name: 'Shorts', exact: true }).click()
    assert.match(await gallery.locator('img').getAttribute('src'), /oF7MRtebWHs/)
    assert.equal(await page.getByRole('button', { name: 'Shorts', exact: true }).getAttribute('aria-pressed'), 'true')
    await page.getByRole('button', { name: 'Todos', exact: true }).click()
    assert.equal(await page.locator('.feedback-card').count(), 15)
    const feedbackImages = await page.locator('.feedback-preview img').evaluateAll(async images => {
      await Promise.all(images.map(async element => {
        const image = new Image()
        image.src = element.src
        await image.decode()
      }))
      return images.length
    })
    assert.equal(feedbackImages, 15)
    await page.getByRole('button', { name: 'Próximo feedback', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('#feedback-track').scrollLeft > 50)
    await page.locator('#feedback-track').evaluate(track => track.scrollTo({ left: track.scrollWidth, behavior: 'instant' }))
    await page.getByRole('button', { name: 'Ampliar feedback 15', exact: true }).click()
    await page.locator('.feedback-dialog[open] img').waitFor()
    assert.match(await page.locator('.feedback-dialog img').getAttribute('src'), /21\.33\.44/)
    await page.keyboard.press('Escape')
    await page.locator('.feedback-dialog').waitFor({ state: 'hidden' })
    assert.ok(await page.getByRole('button', { name: 'Ampliar feedback 15', exact: true }).evaluate(element => element === document.activeElement))
    await page.locator('#feedback-track').evaluate(track => track.scrollTo({ left: 0, behavior: 'instant' }))
    await page.getByRole('button', { name: 'Ampliar feedback 1', exact: true }).click()
    await page.getByRole('button', { name: 'Fechar feedback ampliado' }).click()
    await page.locator('.feedback-dialog').waitFor({ state: 'hidden' })
    await page.locator('#feedbacks').screenshot({ path: fileURLToPath(new URL(`feedbacks-${width}.png`, output)) })
    await page.getByRole('button', { name: /Escreva o Seu Próximo Capítulo/i }).click()
    assert.match(await page.locator('#contact-notice').innerText(), /disponibilizado em breve/)
    await page.getByRole('button', { name: /Escreva o Seu Próximo Capítulo/i }).click()
    const order = await page.locator('main > section').evaluateAll(elements => elements.map(element => element.id || 'hero'))
    assert.deepEqual(order, ['hero', 'jornada', 'acervo', 'grimorio', 'feedbacks', 'epilogo'])
    await page.evaluate(() => window.scrollTo(0, 0))
    const screenshotStyle = '.skip-link:not(:focus){visibility:hidden}'
    await page.screenshot({ path: fileURLToPath(new URL(`viewport-${width}.png`, output)), fullPage: true, style: screenshotStyle })
    await page.locator('.hero').screenshot({ path: fileURLToPath(new URL(`players-hero-${width}.png`, output)), style: screenshotStyle })
    await page.locator('#acervo').screenshot({ path: fileURLToPath(new URL(`players-acervo-${width}.png`, output)), style: screenshotStyle })
    assert.deepEqual(errors, [])
    results.push({ width, ...dimensions, errors, order, controls: 'passed', feedbackImages, feedbackModalAndNavigation: 'passed', youtubeIntegration: 'passed', youtubeIds, presentationId: '9FwdP60SSpc', youtubeNetwork: 'External HTTPS blocked deliberately; playback not checked by this offline audit.' })
    await page.close()
  }
  await writeFile(new URL('results.json', output), JSON.stringify(results, null, 2))
  console.log(JSON.stringify(results, null, 2))
} finally {
  await browser.close()
}
